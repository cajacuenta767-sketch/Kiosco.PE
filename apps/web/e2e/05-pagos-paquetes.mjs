await page.getByRole('button', { name: /Inca Kola 500ml/ }).click()
await page.getByRole('button', { name: /^Cobrar/ }).click()
await page.locator('.metodo', { hasText: 'Yape' }).click()
await page.locator('.pago-digital img.pago-qr').waitFor()
esperar((await page.locator('.pago-numero').innerText()) === '987 654 321', 'al cobrar con Yape sale el número')
await shot(page, '64-cobrar-yape')
await page.getByRole('button', { name: /Mostrar al cliente en grande/ }).click()
await page.locator('.pago-completo').waitFor()
await shot(page, '65-qr-cliente')
await page.locator('.pago-completo').click()
await page.locator('.metodo', { hasText: 'Plin' }).click()
esperar((await page.locator('.pago-digital').count()) === 0, 'Plin sin configurar muestra el aviso, no un QR ajeno')
await page.locator('.metodo', { hasText: 'Yape' }).click()
await page.getByRole('button', { name: /^Confirmar/ }).click()
await page.getByText(/Venta registrada/).waitFor()

// ── Lo de siempre: tras dos fiados iguales, el cliente tiene compra habitual ──
for (let i = 0; i < 2; i++) {
  await page.getByRole('button', { name: /Pan Francés/ }).click()
  await page.getByRole('button', { name: /Pan Francés/ }).click()
  await page.getByRole('button', { name: /Leche Gloria/ }).click()
  await page.getByRole('button', { name: /^Cobrar/ }).click()
  await page.locator('.metodo', { hasText: 'Fiado' }).click()
  if (i === 0) await page.getByPlaceholder(/Sra. Rosa/).fill('Sra. Rosa')
  await page.getByRole('button', { name: /Anotar fiado/ }).click()
  await page.getByText(/Venta registrada/).waitFor()
  await page.waitForTimeout(300)
}
await page.getByRole('button', { name: 'Clientes' }).click()
await page.getByText('Lo de siempre').waitFor()
await page.locator('.item', { hasText: 'Sra. Rosa' }).locator('.item-sub', { hasText: 'Pan' }).waitFor({ timeout: 5000 })
const resumen = await page.locator('.item', { hasText: 'Sra. Rosa' }).locator('.item-sub').innerText()
esperar(resumen.includes('2 Pan Francés') && resumen.includes('1 Leche Gloria'), `lo de siempre de Sra. Rosa: ${resumen}`)
await shot(page, '66-lo-de-siempre')
await page.locator('.item', { hasText: 'Sra. Rosa' }).locator('.item-cuerpo').click()
await page.getByRole('button', { name: /Cobrar S\/ 4[.,]80/ }).waitFor()
esperar(true, 'lo de siempre entra al carrito (2 pan + 1 leche = S/ 4.80)')
await page.getByRole('button', { name: /Cobrar S\/ 4[.,]80/ }).click()
await page.locator('.metodo', { hasText: 'Fiado' }).click()
esperar((await page.locator('select').inputValue()) !== '', 'el cliente queda preseleccionado al fiar')

reportar(errores)
await browser.close()
