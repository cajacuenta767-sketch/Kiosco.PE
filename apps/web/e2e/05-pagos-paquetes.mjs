import { abrirNavegador, celular, capturas, reportar, esperar } from './comun.mjs'
const browser = await abrirNavegador()
const errores = []
const shot = capturas()
const page = await celular(browser, 'A', errores)
const QR_PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAYAAABytg0kAAAAEklEQVR4nGP4z8DwHwyBDCAAABn8BPl6hGmVAAAAAElFTkSuQmCC', 'base64')

// ── Paquetes: six-pack de Pilsen descuenta 6 y cobra S/ 39 ──
const pilsen = page.getByRole('button', { name: /Cerveza Pilsen 630ml/ })
const stockAntes = await pilsen.locator('.tp-stock').innerText()
await page.locator('.tarjeta-producto', { hasText: 'Cerveza Pilsen' }).getByRole('button', { name: /Six-pack/ }).click()
await page.getByRole('button', { name: /Cobrar S\/ 39[.,]00/ }).waitFor()
await shot(page, '60-paquete-carrito')
esperar((await page.locator('.tp-badge').first().innerText()) === '6', 'el six-pack pone 6 unidades en el carrito')
await page.getByRole('button', { name: /Cobrar S\/ 39[.,]00/ }).click()
await page.getByRole('button', { name: /^Confirmar/ }).click()
await page.getByText(/Venta registrada · S\/ 39[.,]00/).waitFor()
await pilsen.locator('.tp-stock', { hasText: '6 und' }).waitFor({ timeout: 5000 }).catch(() => {})
const stockDespues = await pilsen.locator('.tp-stock').innerText()
esperar(stockAntes === '12 und' && stockDespues === '6 und', `el stock baja 6 (${stockAntes} → ${stockDespues})`)

// ── Precio por paquete editable en el producto ──
await page.getByRole('button', { name: 'Stock', exact: true }).click()
await page.locator('.item-cuerpo', { hasText: 'Sublime' }).click()
await page.getByRole('button', { name: /Agregar paquete/ }).click()
await page.getByLabel('Nombre del paquete').fill('Caja x10')
await page.getByLabel('Unidades por paquete').fill('10')
await page.getByLabel('Precio del paquete').fill('18')
await shot(page, '61-paquete-form')
await page.getByRole('button', { name: 'Guardar' }).click()
await page.locator('.modal').waitFor({ state: 'hidden' })
await page.getByRole('button', { name: 'Vender', exact: true }).click()
await page.locator('.tarjeta-producto', { hasText: 'Sublime' }).getByRole('button', { name: /Caja x10 S\/ 18/ }).waitFor()
esperar(true, 'el paquete nuevo aparece en Vender')

// ── Lista de precios ──
await page.getByRole('button', { name: 'Stock', exact: true }).click()
await page.getByRole('button', { name: /Lista de precios/ }).click()
await page.locator('.lista-precios').waitFor()
await shot(page, '62-lista-precios')
const filas = await page.locator('.lista-precios tr').count()
esperar(filas > 30, `lista de precios con ${filas} filas`)
const wa = await page.locator('.lista-precios').locator('..').locator('a.btn-whatsapp').getAttribute('href')
esperar(wa.includes(encodeURIComponent('Six-pack (x6)')), 'el texto de WhatsApp incluye los paquetes')
