await page.getByRole('button', { name: /^Yape/ }).click()
await page.locator('.medio-pago input[type=file]').first().setInputFiles({ name: 'qr.png', mimeType: 'image/png', buffer: QR_PNG })
await page.locator('.qr-mini').waitFor()
await page.getByLabel('Número de Yape').fill('987654321')
await page.getByPlaceholder(/Carmen R/).fill('Carmen R.')
await shot(page, '63-yape-config')
await page.getByRole('button', { name: 'Guardar Yape' }).click()
await page.getByText('Yape guardado').waitFor()
